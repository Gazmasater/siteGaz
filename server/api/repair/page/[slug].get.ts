function cap(s: string): string {
  if (!s) return s;
  return s.slice(0, 1).toUpperCase() + s.slice(1);
}

function normCode(codeRaw: string): string {
  const c = codeRaw.trim().toUpperCase();
  if (!c) return "F??";
  return /^[A-Z]/.test(c) ? c : `F${c}`;
}

function normCodeForBrand(codeRaw: string, brandSlug: string): string {
  const c = codeRaw.trim().toUpperCase();
  if (!c) return brandSlug === "navien" ? "??" : "F??";
  if (brandSlug === "navien") return c.startsWith("E") ? c.replace(/^E0*/, "").padStart(c.replace(/^E0*/, "").length <= 2 ? 2 : 3, "0") : c;
  if (brandSlug === "viessmann") return c === "03-SERV" ? "03 + SERV" : c;
  return normCode(c);
}

function regionName(regionSlug: string): string {
  const map: Record<string, string> = {
    lipeck: "Липецк",
    moscow: "Москва",
    spb: "Санкт-Петербург",
  };
  return map[regionSlug] || cap(regionSlug);
}

